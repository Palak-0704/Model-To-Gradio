def _trim(value: Any, limit: int = 300) -> str:
    """Repository-derived text as a short, single-purpose string: control characters removed, backticks neutralised so it
    can never close or open a code fence in the request. The ``<<<`` of the data markers is defused too, so repository text
    cannot fake the end of the data block."""
    return re.sub(r"[\x00-\x08\x0b-\x1f\x7f]", " ", str(value)).replace("`", "'").replace("<<<", "<<")[:limit]


def _jsonable(value: Any, depth: int = 0) -> Any:
    if value is None or isinstance(value, (bool, int)):
        return value
    if isinstance(value, float):
        return round(value, 4)
    if isinstance(value, str):
        return _trim(value)
    if depth >= 3:
        return _trim(value, 120)
    if isinstance(value, (list, tuple, set)):
        return [_jsonable(v, depth + 1) for v in list(value)[:20]]
    if isinstance(value, dict):
        return {_trim(k, 60): _jsonable(v, depth + 1) for k, v in list(value.items())[:30]}
    return _trim(value, 120)


def _safe_tree(value: Any, depth: int = 0) -> Any:
    """Like ``_jsonable`` but for the nested, longer REA evidence: same neutralisation of backticks/markers, deeper and longer."""
    if value is None or isinstance(value, (bool, int)):
        return value
    if isinstance(value, float):
        return round(value, 4)
    if isinstance(value, str):
        return _trim(value, 1500)
    if depth >= 8:  # deep enough for combined_analysis -> capabilities -> requirements -> {value, source} to keep lists/ints intact
        return _trim(value, 120)
    if isinstance(value, (list, tuple)):
        return [_safe_tree(v, depth + 1) for v in list(value)[:20]]
    if isinstance(value, dict):
        return {_trim(k, 60): _safe_tree(v, depth + 1) for k, v in list(value.items())[:30]}
    return _trim(value, 120)


def _dict_items(value: Any) -> List[Dict[str, Any]]:
    """The dict entries of a list; anything that is not a list, and any entry that is not a dict, is ignored (malformed REA data)."""
    return [v for v in value if isinstance(v, dict)] if isinstance(value, list) else []


def _rea_facts(a: Analysis) -> Dict[str, Any]:
    """The platform's own REA inspection (run before generation, not by OpenCode) as data. Only what REA really did is stated."""
    rea = a.rea
    if not isinstance(rea, dict) or not rea:
        return {"status": "not_invoked", "reason": "No REA inspection was run for this analysis.", "tools_executed": []}
    calls = _dict_items(rea.get("calls"))
    summaries = _dict_items(rea.get("header_summaries"))
    findings = rea.get("findings") if isinstance(rea.get("findings"), list) else []
    server = rea.get("server") if isinstance(rea.get("server"), dict) else None
    return _safe_tree({
        "status": rea.get("status"),
        "reason": rea.get("reason"),
        "server": server,
        "tools_executed": [c.get("tool") for c in calls],
        "files_inspected": [{"file": s.get("file"), "tensor_count": s.get("tensor_count"), "parameters": s.get("parameters"),
                             "dtypes": s.get("dtypes")} for s in summaries[:3]],
        "findings": [f for f in findings if isinstance(f, (str, int, float))][:6],
        "calls": [{"tool": c.get("tool"), "target": c.get("target"), "ok": c.get("ok"), "error": c.get("error"),
                   "output": str(c.get("output") or "")[:1500]} for c in calls if c.get("tool") == "inspect_model_artifact"][:3],
    })


def _combined_facts(a: Analysis) -> Any:
    """The unified Python-analyzer + REA report (``Analysis.combined_analysis``) as sanitised data. An Analysis that did not come from
    ``analyze()`` has none stored, so it is derived here; if even that fails, the model is told the report is unavailable."""
    report = a.combined_analysis
    if not isinstance(report, dict):
        try:
            report = build_combined_analysis(a)
        except Exception as exc:
            report = {"schema_version": COMBINED_SCHEMA_VERSION, "status": "unavailable",
                      "error": f"The combined report could not be built ({type(exc).__name__})."}
    return _safe_tree(report)


def _capability_facts(a: Analysis, c: Capability, multi: bool) -> Dict[str, Any]:
    """One capability as data for OpenCode: what the evidence says, its modalities and the function it must get. The reference
    components (when TASK_IO has the task) and the modality-suggested components are hints, never a template."""
    chat = bool(c.chat) if multi else bool(a.task == "text-generation" and a.chat)
    key = "text-generation:chat" if (c.name == "text-generation" and chat) else c.name
    spec = TASK_IO.get(key)
    return {
        "name": c.name, "role": c.role, "status": c.status, "confidence": c.confidence, "evidence_tier": c.tier,
        "input_modalities": c.input_modalities, "output_modalities": c.output_modalities, "chat": chat,
        "function_name": ("chat_fn" if chat else "predict") + ("_" + slug(c.name) if multi else ""),
        "advisory": c.advisory,
        "reference_components": ({"inputs": [{"name": n, "component": f"gr.{k}"} for n, k in spec["in"]],
                                  "outputs": [{"name": n, "component": f"gr.{k}"} for n, k in spec["out"]]} if spec else None),
        "suggested_components": {"inputs": suggested_components(c.input_modalities), "outputs": suggested_components(c.output_modalities)},
        "evidence": [{k: e.get(k) for k in ("tier", "signal", "source", "detail", "weight")} for e in c.evidence[:4]],
        "certainty": c.certainty, "certainty_reason": c.certainty_reason,
        "requirements": c.requirements,  # {name: {"value", "source"}} stated by the model's own config/preprocessor/tokenizer files
    }


def _evidence_facts(a: Analysis) -> Any:
    """The evidence-collection digest (per-item status, provenance, errors, tensor-header summaries, limitations) as sanitised data. An
    analysis without one says so explicitly: absent evidence is reported as absent, never as confirmed."""
    if isinstance(a.evidence, dict) and a.evidence:
        return _safe_tree(a.evidence)
    return {"status": "not_collected", "reason": "No evidence collection result is attached to this analysis; nothing beyond the other facts is established."}


def _facts(a: Analysis) -> Dict[str, Any]:
    """The analysis (and the inspection evidence it carries) as plain data for the model."""
    ref = a.model_ref
    exp_in, exp_out = _expected_io(a)
    hw = a.hardware
    tier_rank = {"authoritative": 0, "structural": 1}
    evidence = sorted(a.task_evidence, key=lambda e: (tier_rank.get(e.tier, 2), -e.weight))[:8]
    prequant = a.quantization == "bitsandbytes"
    facts = _jsonable({
        "model_id": ref.repo_id,
        "revision": a.revision,
        "task": a.task,
        "task_confidence": a.task_confidence,
        "library": a.library,
        "chat_model": bool(a.task == "text-generation" and a.chat),
        "frameworks": a.frameworks,
        "input_modalities": a.input_modalities,
        "output_modalities": a.output_modalities,
        "expected_inputs": [{"name": n, "component": c} for n, c in exp_in],
        "expected_outputs": [{"name": n, "component": c} for n, c in exp_out],
        "platform_constants": {
            "TASK": _pipeline_task(a), "TRUST_REMOTE_CODE": bool(a.trust_remote_code), "USE_SAFETENSORS": bool(a.use_safetensors),
            "PREQUANTIZED": prequant, "LOAD_IN_4BIT_RECOMMENDED": bool(a.load_in_4bit_recommended and not prequant),
        },
        "quantization": a.quantization,
        "gated": a.gated,
        "license": a.license,
        "hardware": {"recommended_runtime": hw.recommended_runtime, "est_vram_gb_fp16": hw.est_vram_gb_fp16,
                     "params": hw.params, "params_source": hw.params_source},
        "pip_dependencies": a.dependencies,
        "ui_hints": a.ui_hints,
        "warnings": a.warnings[:8],
        "uncertainties": a.uncertainties[:6],
        "task_evidence": [{"tier": e.tier, "signal": e.signal, "source": e.source, "detail": e.detail, "weight": e.weight}
                          for e in evidence],
    })
    ifc = interface_capabilities(a)
    multi = len(ifc) > 1
    facts["multi_capability"] = multi
    facts["capabilities"] = _safe_tree([_capability_facts(a, c, multi) for c in ifc])  # each gets its OWN interface
    facts["ui_contract"] = {
        "multi_capability_layout": "horizontal_tabs" if multi else "single_interface",
        "tabs_container": "gr.Tabs" if multi else None,
        "one_tab_per_capability": multi,
        "shared_model_loader": True,
        "loading_feedback": True,
    }
    facts["not_built_capabilities"] = _safe_tree(  # uncertain / not-built: never get an interface
        [{"name": c.name, "role": c.role, "status": c.status, "confidence": c.confidence, "reason": c.status_reason}
         for c in a.capabilities if c not in ifc][:10])
    cfg = (a.model_evidence or {}).get("config") or {}
    facts["architecture"] = _safe_tree({"architectures": cfg.get("architectures"), "model_type": cfg.get("model_type"),
                                        "sub_configs": cfg.get("sub_configs"), "library": a.library})
    me = _safe_tree(a.model_evidence or {})
    if isinstance(me, dict):
        me["model_card_excerpt"] = redact_secrets(str(me.get("model_card_excerpt") or ""))
    facts["model_evidence"] = me  # bounded, whitelisted config/tokenizer/file/diffusers digest
    facts["rea_inspection"] = _rea_facts(a)  # deeper/longer than _jsonable allows; sanitised by _safe_tree
    facts["combined_analysis"] = _combined_facts(a)  # Python findings and REA findings side by side, with conflicts and recommendations
    facts["evidence"] = _evidence_facts(a)  # metadata-first evidence collection: what was collected, from where, and what could not be
    return facts


