def build_native_request(a: Analysis) -> str:
    """Native counterpart of ``build_request`` using the same REA/evidence data channel.

    It is callable only after the platform's format adapter and runtime-validation gate
    establish a concrete contract; OpenCode never receives authority to discover one.
    """
    facts = _facts(a)
    facts["native_inference_contract"] = _safe_tree((a.native or {}).get("inference_contract") or {})
    facts["native_runtime_validation"] = _safe_tree((a.native or {}).get("runtime_validation") or {})
    facts["native_generation_evidence"] = _safe_tree((a.native or {}).get("generation_evidence") or {})
    facts["approved_adapter"] = (a.native or {}).get("approved_loader")
    return "\n".join([
        "# Model-to-Gradio: write two native inference code sections",
        "Write exactly m2g:setup and m2g:ui Python fences, as in the normal platform contract.",
        "This is a GitHub-native artifact, not a Hugging Face model. Do NOT use transformers, HF_TOKEN, torch.hub.load,",
        "trust_remote_code, repository imports, repository scripts, pickle weights, downloads, random tensors, dummy predictions,",
        "or placeholder errors. Use ONLY the approved_adapter and the exact artifact/schema/fixture facts below.",
        "If ARTIFACT_AUTHORIZED is false, get_model must raise a clear RuntimeError before attempting any model load.",
        "Implement verified preprocessing, actual inference, verified postprocessing and Gradio presentation of actual outputs.",
        "If a fact is unknown, do not invent it; the platform will reject the output.",
        f"{_FENCE}python m2g:setup", "<section 1 code>", _FENCE, "",
        f"{_FENCE}python m2g:ui", "<section 2 code>", _FENCE, DATA_BEGIN,
        f"{_FENCE}json m2g:facts", json.dumps(facts, indent=2, ensure_ascii=True), _FENCE, DATA_END, "",
    ])


