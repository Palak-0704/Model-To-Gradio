def _loading_strategy_guidance(a: Analysis) -> str:
    """Choose a stable task-family loading contract instead of a removed pipeline task."""
    if a.library == "diffusers":
        return ("This is a diffusers model: load it with DiffusionPipeline.from_pretrained (never transformers.pipeline), place it "
                "with DEVICE/DTYPE, and call the pipeline object directly.")
    if a.library == "sentence-transformers":
        return ("This is a sentence-transformers model: load it with SentenceTransformer (never transformers.pipeline) and use "
                "its encode() method.")
    # every capability that gets an interface counts, not only the primary one (a task-conditioned mode shares the model); a mode
    # whose input is not text (translation on an audio model) is not a text-to-text task and does not choose this loading contract
    tasks = _build_tasks(a)
    if a.library == "transformers" and tasks & _NO_PIPELINE_TASKS:
        return (
            "This task family must not depend on a transformers pipeline registry entry. "
            "Load the appropriate AutoModel class and AutoTokenizer/processor and implement "
            "inference directly with tokenizer inputs and model.generate (or the documented "
            "task forward method); this remains valid if the pipeline task is removed."
        )
    return (
        "Use a pipeline only when model evidence and the runtime probe establish that the "
        "task is registered. Otherwise use the documented AutoModel class with its tokenizer "
        "or processor and direct inference."
    )


def interface_capabilities(a: Analysis) -> List[Capability]:
    """The capabilities that get their own interface: evidence-SUPPORTED ones only, primary first. Uncertain capabilities (weak or
    heuristic evidence, unknown task, modality-only, contradicted) never do. An Analysis that carries no capability list (older JSON,
    hand-built) is the legacy single-task case: its one derived primary capability is used, as before."""
    if a.capabilities:
        return [c for c in a.capabilities if c.builds_interface and c.status == "supported"]
    return effective_capabilities(a)


# Task families whose transformers pipeline entry has been removed or may be removed: load AutoModel + tokenizer directly.
_NO_PIPELINE_TASKS = frozenset({"text2text-generation", "summarization", "translation", "question-answering"})


def _takes_text(c: Capability) -> bool:
    """True when the capability takes text (or its input modalities are unknown). A task-conditioned MODE of a non-text model, for
    example ``translation`` on an audio model (``input_modalities == ['audio']``), shares the primary model: the standalone
    text-to-text loading and I/O contract that its name alone would select does not apply to it."""
    mods = list(c.input_modalities or [])
    return not mods or "text" in mods


def _build_tasks(a: Analysis) -> set:
    """The task names this app must build; they choose the task-specific guidance (loading strategy, contracts, helpers)."""
    return {c.name for c in interface_capabilities(a) if c.name not in _NO_PIPELINE_TASKS or _takes_text(c)} | {a.task}

