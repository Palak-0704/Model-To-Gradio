def _clean(text: str, limit: int = 160) -> str:
    """Keep header text harmless: no quotes, backslashes, newlines or control characters."""
    return re.sub(r"[^\w .,:;()/+=%<>'\-\[\]@?!*&|~]+", "", str(text).replace("\n", " "))[:limit]


def _expected_io(a: Analysis):
    key = "text-generation:chat" if (a.task == "text-generation" and a.chat) else a.task
    spec = TASK_IO.get(key)  # a reusable REFERENCE only: a capability without an entry is still generated
    if spec is None:
        return [], []
    return ([(n, f"gr.{k}") for n, k in spec["in"]], [(n, f"gr.{k}") for n, k in spec["out"]])


