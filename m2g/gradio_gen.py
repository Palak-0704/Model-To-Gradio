def _build_header(a: Analysis) -> str:
    ref = a.model_ref
    hw = a.hardware
    hw_txt = _clean(hw.recommended_runtime) + (f" (about {hw.est_vram_gb_fp16} GB VRAM in fp16)" if hw.est_vram_gb_fp16 else "")
    warn_txt = "\n".join("WARNING: " + _clean(w, 200) for w in a.warnings[:8] if w) or "Warnings: none"
    via_github = a.source.kind == "github" and a.model_source is not None
    prequant = a.quantization == "bitsandbytes"
    fourbit = bool(a.load_in_4bit_recommended and not prequant)
    subs = {
        "@@MODEL_ID_TXT@@": _clean(ref.repo_id), "@@TASK_TXT@@": _clean(_task_header(a)),
        "@@URL_TXT@@": _clean(ref.canonical_url) + (f" (linked from GitHub repository {_clean(a.source.canonical_url)})" if via_github else ""),
        "@@REV_TXT@@": _clean(a.revision or "default branch (unpinned)"), "@@HW_TXT@@": hw_txt, "@@WARN_TXT@@": warn_txt,
        # repr() output is a valid, escaped Python literal: repository-controlled values cannot break out of it
        "@@MODEL_ID@@": repr(ref.repo_id), "@@REVISION@@": repr(a.revision), "@@TASK@@": repr(_pipeline_task(a)),
        "@@TRUST@@": repr(bool(a.trust_remote_code)), "@@SAFETENSORS@@": "True" if a.use_safetensors else "False",
        "@@PREQUANT@@": repr(prequant), "@@FOURBIT@@": repr(fourbit),
        "@@NO_SAFETENSORS@@": repr(bool(a.ui_hints.get("safetensors_unavailable"))),
    }
    header = _HEADER
    for k, v in subs.items():
        header = header.replace(k, v)
    return header


def linked_pickle_refusal(a: Analysis) -> Optional[str]:
    """Plain-language refusal for an app that would be generated THROUGH a GitHub repository from a linked Hugging Face model that has
    only pickle-based weights (no verified safetensors) and no explicit consent to unpickle. Independent of the analyzer's own check, so a
    hand-built or tampered analysis is refused here too. A direct Hugging Face analysis is not affected: it may be generated as a
    candidate whose runtime keeps pickle loading off (``ALLOW_PICKLE_WEIGHTS`` consent)."""
    if a.source.kind == "github" and a.model_source is not None and a.ui_hints.get("safetensors_unavailable") and a.use_safetensors:
        return ("The linked Hugging Face model only has pickle-based weight files and no verified safetensors weights. Unpickling can run "
                "arbitrary code, so an app is not generated for it through a GitHub repository. You can review the model yourself and "
                "analyse its Hugging Face URL directly; the generated app will then still ask for your explicit consent before it "
                "loads any pickle file.")
    return None


def generate_app(a: Analysis, settings: Optional[Settings] = None, adapter: Optional[OpenCodeAdapter] = None) -> str:
    """Return the complete app.py for a supported analysis. Raises GenerationError for anything that goes wrong; there is no
    fallback to another generator. ``adapter`` is only for tests; normally the configured OpenCode CLI is used."""
    if not a.generatable:
        raise GenerationError(f"Cannot generate an app for status '{a.status}': " + "; ".join([*a.reasons, *a.generation_blocked_reasons]))
    refusal = linked_pickle_refusal(a)
    if refusal:
        raise GenerationError("Cannot generate an app: " + refusal)
    # The model to load is a Hugging Face repository: the analysed URL itself, or (for a GitHub analysis) the repository's own
    # linked Hugging Face model that the analyzer identified and fully analysed. The GitHub repository is never loaded.
    check_analysis_integrity(a, settings)
    if a.origin == "github-native":
        from .native_readiness import require_code_generation_prerequisites
        native = a.native or {}
        try:
            require_code_generation_prerequisites(native.get("generation_evidence") or {})
        except ValueError:
            return finalize_native_scaffold(a, build_native_scaffold(a), settings)
        if not native.get("approved_loader") or not native.get("inference_contract"):
            return finalize_native_scaffold(a, build_native_scaffold(a), settings)
        result = (adapter or _new_adapter()).run(build_native_request(a))
        if not result.ok:
            raise GenerationError(f"OpenCode could not generate the native app ({result.error}): {result.message}")
        setup, ui = extract_sections(result.text, getattr(result, "text_parts", None))
        for label, source in (("native model setup", setup), ("native Gradio UI", ui)):
            _reject_unsafe_constructs(label, _parse_section(label, source))
            forbidden = ("torch.hub", "trust_remote_code=True", "NotImplementedError", "random.", "dummy")
            if any(token in source for token in forbidden):
                raise GenerationError(f"The {label} section violates the native inference security contract.")
        code = (_build_native_header(a).rstrip("\n") + "\n\n\n" + _SETUP_MARK + "\n" + setup.strip("\n") + "\n\n\n"
                + _UI_MARK + "\n" + ui.strip("\n") + "\n" + _LAUNCH)
        return finalize_native_generated_code(a, code, settings)
    ref = a.model_ref
    if ref.kind != "huggingface":
        raise GenerationError("Only Hugging Face models can be generated. A GitHub repository needs an identified, supported "
                              "linked Hugging Face model (its own code is never run).")
    try:
        validate_repo_id(ref.repo_id)
        if a.revision:
            validate_revision(a.revision)
    except SecurityError as exc:
        raise GenerationError(str(exc))

    header = _build_header(a)
    request = build_request(a)
    try:
        assert_no_secrets(request, settings)
    except SecurityError:
        raise GenerationError("The generation request contains something that looks like a credential; it was not sent to OpenCode.")

    result = (adapter or _new_adapter()).run(request)
    if not result.ok:
        raise GenerationError(f"OpenCode could not generate the app ({result.error}): {result.message}")
    setup, ui = extract_sections(result.text, getattr(result, "text_parts", None))
    for label, source in (("model setup", setup), ("Gradio UI", ui)):
        if _SETUP_MARK in source or _UI_MARK in source:
            raise GenerationError(f"The {label} section contains a platform section-marker line.")
        _reject_unsafe_constructs(label, _parse_section(label, source))

    code = (header.rstrip("\n") + "\n\n\n"
            "# ---- Model setup and loading (written by OpenCode) ----\n" + setup.strip("\n") + "\n\n\n"
            "# ---- Gradio UI and inference (written by OpenCode) ----\n" + ui.strip("\n") + "\n" + _LAUNCH)
    return finalize_generated_code(a, code, settings)


def finalize_generated_code(a: Analysis, code: str, settings: Optional[Settings] = None) -> str:
    """Everything that happens to assembled app code after OpenCode wrote it: the static validation, the interface and loader checks and
    the dependency derivation. ``generate_app`` ends here, and so does the reuse of an existing package's code (its OpenCode call is
    skipped, its checks are not). Raises GenerationError; sets ``a.dependencies`` / ``a.dependency_evidence`` like a fresh generation."""
    if a.origin == "github-native":
        return (finalize_native_scaffold(a, code, settings) if NATIVE_MARK in code
                else finalize_native_generated_code(a, code, settings))
    ifc = interface_capabilities(a)
    skipped = [c.name for c in a.capabilities if c not in ifc]
    try:
        validate_app_code(code, settings)  # the same static checks the pipeline applies; nothing is executed
        validate_capability_interfaces(code, [(c.name, bool(c.chat)) for c in ifc], skipped)
        check_generated_interface(code, ifc, library=a.library)  # components match the modalities and the library's loader; errors go through gr.Error
        assert_no_secrets(code, settings)
    except (ValidationError, SecurityError) as exc:
        raise GenerationError(f"OpenCode produced code that failed validation: {exc}")
    loaders = {n.name for n in ast.parse(code).body if isinstance(n, ast.FunctionDef)} & {"get_model", "get_pipe"}
    if not loaders:  # the Colab notebook loads the model through this function
        raise GenerationError("OpenCode's setup section must define a module-level get_model() loader function.")
    # The package is written as loader.py + app.py. Validate that exact pair (as one program) so a missing import between the two
    # files, or anything the split changed, is caught here and never written.
    try:
        loader_py, app_py = split_app_code(code)
        validate_app_code(combine_package_source(app_py, loader_py), settings)
    except ValidationError as exc:
        raise GenerationError(f"The loader.py / app.py pair failed validation: {exc}")
    # requirements follow the imports the app really uses (controlled allowlist); the pipeline and the notebook read a.dependencies
    a.dependencies, a.dependency_evidence = _with_import_requirements(a, code)
    return code


def generate_requirements(a: Analysis, app_code: Optional[str] = None) -> str:
    if not a.generatable:
        raise GenerationError("No requirements for an unsupported analysis.")
    deps = _with_import_requirements(a, app_code)[0] if app_code else a.dependencies
    lines = sorted({validate_pip_requirement(_compatibility_requirement(d, a)) for d in deps})
    return "\n".join(lines) + "\n"
