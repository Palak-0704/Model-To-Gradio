def _module_names(tree: ast.Module) -> set:
    """Names bound at module level by defs, assignments and imports."""
    names: set = set()
    for n in tree.body:
        if isinstance(n, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            names.add(n.name)
        elif isinstance(n, (ast.Assign, ast.AnnAssign)):
            for t in (n.targets if isinstance(n, ast.Assign) else [n.target]):
                names.update(s.id for s in ast.walk(t) if isinstance(s, ast.Name))
        elif isinstance(n, (ast.Import, ast.ImportFrom)):
            names.update((al.asname or al.name).split(".")[0] for al in n.names)
    return names


def split_app_code(code: str) -> Tuple[str, str]:
    """(loader.py text, app.py text) cut from the single-module source that ``generate_app`` validated. loader.py is the platform header
    plus OpenCode's setup/loading/inference section; app.py holds the UI section and the launch block and imports, by explicit name,
    exactly the loader names the UI uses. Nothing is regenerated: both files are slices of the same validated text."""
    i, j = code.find(_SETUP_MARK), code.find(_UI_MARK)
    if not 0 <= i < j or not code.endswith(_LAUNCH):
        raise GenerationError("The generated app does not have the expected setup/UI structure and cannot be split into loader.py and app.py.")
    header, setup, ui = code[:i], code[i:j], code[j:len(code) - len(_LAUNCH)]
    loader_names, ui_tree = _module_names(ast.parse(header + setup)), ast.parse(ui)
    for n in ast.walk(ui_tree):
        if isinstance(n, (ast.Global, ast.Nonlocal)) and set(n.names) & loader_names:
            raise GenerationError("The Gradio UI section rebinds a name that the model setup section defines ("
                                  + ", ".join(sorted(set(n.names) & loader_names)) + "); keep that state inside loader.py.")
    used = {n.id for n in ast.walk(ui_tree) if isinstance(n, ast.Name) and isinstance(n.ctx, ast.Load)}
    needed = ((used & loader_names) - _module_names(ui_tree) - {"os", "gr", "torch"}) | (loader_names & {"get_model", "get_pipe"})
    imports = "from loader import (\n" + "".join(f"    {name},\n" for name in sorted(needed)) + ")\n"
    loader_py = (header + setup).rstrip("\n") + "\n"
    app_py = (NATIVE_APP_HEADER if NATIVE_MARK in header else _APP_HEADER) + imports + "\n\n" + ui.strip("\n") + "\n" + _LAUNCH
    return loader_py, app_py


def join_package_code(loader_py: str, app_py: str) -> str:
    """The single-module source ``split_app_code`` would cut into exactly this loader.py / app.py pair (its inverse), so the code of an
    existing package can go through the same checks and the same notebook/requirements generation as freshly generated code.
    Raises GenerationError when the pair is not one this generator wrote (then nothing is reused)."""
    j = app_py.find(_UI_MARK)
    if not app_py.startswith((_APP_HEADER, NATIVE_APP_HEADER)) or j < 0 or not app_py.endswith(_LAUNCH):
        raise GenerationError("app.py does not have the structure this generator writes; it cannot be reused.")
    ui = app_py[j:len(app_py) - len(_LAUNCH)]
    code = loader_py.rstrip("\n") + "\n\n\n" + ui.rstrip("\n") + "\n" + _LAUNCH
    if split_app_code(code) != (loader_py, app_py):
        raise GenerationError("loader.py and app.py do not round-trip to the generated structure; they cannot be reused.")
    return code


