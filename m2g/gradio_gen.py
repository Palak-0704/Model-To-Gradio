def _uses_transformers_pipeline(tree: ast.AST) -> bool:
    """``from transformers import pipeline`` or ``transformers.pipeline(...)``. A variable that merely happens to be called
    ``pipeline`` (``pipeline = DiffusionPipeline.from_pretrained(...)``) is not a use of the transformers function."""
    for n in ast.walk(tree):
        if isinstance(n, ast.ImportFrom) and (n.module or "").split(".")[0] == "transformers" and any(
                al.name == "pipeline" for al in n.names):
            return True
        if isinstance(n, ast.Attribute) and n.attr == "pipeline" and isinstance(n.value, ast.Name) and n.value.id == "transformers":
            return True
    return False


def _check_required_inputs(tree: ast.AST, caps: List[Capability]) -> None:
    """A task that cannot work with one input must be wired to a handler that takes them separately. Only tasks with a TASK_IO
    reference are checked, and never beyond what that reference lists. A handler that is not found, or that takes ``*args``, is not
    guessed at (``validate_capability_interfaces`` is what requires the handlers to exist)."""
    multi = len(caps) > 1
    defs: Dict[str, ast.FunctionDef] = {}
    for n in ast.walk(tree):
        if isinstance(n, ast.FunctionDef):
            defs.setdefault(n.name, n)
    for c in caps:
        required = _REQUIRED_INPUTS.get(c.name)
        spec = TASK_IO.get(c.name)
        if not required or not spec:
            continue
        need, what = min(required[0], len(spec["in"])), required[1]
        suffix = "_" + slug(c.name) if multi else ""
        for fname in ("predict" + suffix, "chat_fn" + suffix):
            fn = defs.get(fname)
            if fn is None or fn.args.vararg is not None:
                continue
            given = len(fn.args.posonlyargs) + len(fn.args.args)
            if given < need:
                raise ValidationError(
                    f"Capability '{c.name}' needs {what} as separate inputs, but its handler {fname}() takes {given}; "
                    f"a generic single-input interface is not accepted.")


def check_generated_interface(code: str, caps: List[Capability], library: Optional[str] = None) -> None:
    """Static checks (nothing is executed) that the generated UI is model-specific and handles errors.

    * every non-text modality of an interface capability needs a matching Gradio component (union over all capabilities; a per-tab
      check would need to resolve component wiring, which is not attempted);
    * the app must be able to raise ``gr.Error`` (input validation / model failures), as the request requires;
    * a task that cannot work with one input (question + context, text + candidate labels, ...) needs a handler with that many inputs;
    * a diffusers / sentence-transformers model is not loaded through ``transformers.pipeline``.
    Raises ValidationError."""
    tree = ast.parse(code)
    used = set()
    for n in ast.walk(tree):
        if isinstance(n, ast.Attribute) and isinstance(n.value, ast.Name) and n.value.id == "gr":
            used.add(n.attr)
        elif isinstance(n, ast.ImportFrom) and (n.module or "").split(".")[0] == "gradio":
            used.update(al.name for al in n.names)
        elif isinstance(n, ast.Call):
            f = n.func
            if (f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")) == "ChatInterface" and any(
                    k.arg == "multimodal" for k in n.keywords):
                used.add("MultimodalTextbox")  # a multimodal chat box accepts uploaded images/audio/video
    for c in caps:
        for direction, mods in (("in", c.input_modalities), ("out", c.output_modalities)):
            for m in mods:
                accepted = _MODALITY_COMPONENTS.get((direction, m))
                if accepted and not (accepted & used):
                    raise ValidationError(
                        f"Capability '{c.name}' has {m} {'input' if direction == 'in' else 'output'}, but the app uses no matching "
                        f"Gradio component (one of: {', '.join('gr.' + x for x in sorted(accepted))}); a generic text interface is not accepted.")
    if library in _LIBRARY_LOADERS and _uses_transformers_pipeline(tree):
        raise ValidationError(
            f"This is a {library} model: load it with {_LIBRARY_LOADERS[library]}, not with transformers.pipeline.")
    _check_required_inputs(tree, caps)
    raises_error = any(
        isinstance(n, ast.Raise) and n.exc is not None
        and (n.exc.func if isinstance(n.exc, ast.Call) else n.exc).__class__ is ast.Attribute
        and (n.exc.func if isinstance(n.exc, ast.Call) else n.exc).attr == "Error"
        for n in ast.walk(tree))
    if not raises_error:
        raise ValidationError("The app never raises gr.Error, so invalid input and model failures are not reported to the user.")


def _req_name(req: str) -> str:
    return re.split(r"[<>=!~\[;\s]", str(req).strip(), maxsplit=1)[0].lower().replace("_", "-")


def _with_import_requirements(a: Analysis, code: str) -> Tuple[List[str], Dict[str, str]]:
    """The analysis' dependencies plus the pip packages for the imports the generated app really uses (controlled allowlist in
    validate.IMPORT_PIP_ALLOWLIST). Nothing existing is dropped or loosened; unsupported imports are rejected, never installed."""
    try:
        # imports give most packages; symbols such as BitsAndBytesConfig / load_in_4bit need bitsandbytes without ever importing it
        derived = ([(m, s, "imported by") for m, s in imports_to_requirements(code)]
                   + [(m, s, "needed by the symbols used in") for m, s in symbols_to_requirements(code)])
    except ValidationError as exc:
        raise GenerationError(f"The generated app uses an unsupported or unsafe dependency: {exc}")
    deps, why = list(a.dependencies), dict(a.dependency_evidence)
    have = {_req_name(d) for d in deps}
    for mod, spec, how in derived:
        if mod == "transformers":
            spec = f"transformers>={a.min_transformers}"
        if _req_name(spec) in have:
            continue
        try:
            req = validate_pip_requirement(spec)
        except SecurityError as exc:
            raise GenerationError(f"Unsafe requirement for import '{mod}': {exc}")
        deps.append(req)
        have.add(_req_name(req))
        why[re.split(r"[<>=!~\[]", req)[0]] = f"{how} the generated app.py ({mod})"
    return deps, why


_GENERATED_COMPATIBILITY_MAX = {
    # These upper bounds are API compatibility ceilings for the generated
    # templates, not package downgrades. A future major release must pass the
    # runtime probes before it can be selected for a generated application.
    "gradio": "<7",
    "torch": "<3",
    "transformers": "<5",
    "diffusers": "<1",
    "accelerate": "<2",
    "sentence-transformers": "<4",
    "safetensors": "<1",
    "bitsandbytes": "<1",
}


def _compatibility_requirement(requirement: str, a: Analysis) -> str:
    """Add a tested major-version ceiling to platform-owned runtime packages."""
    name = _req_name(requirement)
    maximum = _GENERATED_COMPATIBILITY_MAX.get(name)
    if not maximum or "<" in requirement:
        return requirement
    if name == "transformers":
        return f"transformers>={a.min_transformers},{maximum}"
    if requirement == name:
        return f"{name}{maximum}"
    return f"{requirement},{maximum}"


def _task_header(a: Analysis) -> str:
    names = [c.name for c in interface_capabilities(a)]
    return ", ".join(names) if len(names) > 1 else str(a.task)


def _check_native_integrity(a: Analysis, settings: Settings) -> None:
    """Integrity of an independent GitHub model analysis (``origin == 'github-native'``): it stands on its own recorded evidence and never
    on a Hugging Face model. Defence in depth: the evidence gate is re-derived from the recorded signals, not trusted from the flag."""
    n = a.native or {}
    if a.source.kind != "github" or a.model_source is not None:
        raise GenerationError("Analysis of an independent GitHub model must come from a GitHub source and carry no separate model source.")
    if a.status != "supported_with_warnings" or not n.get("eligible") or not n.get("scaffold_only"):
        raise GenerationError("Analysis does not record eligible independent GitHub model evidence.")
    signals = set(n.get("signals") or [])
    if not (signals & {"weight-files", "model-config"}) or not ("ml-framework" in signals or {"weight-files", "model-config"} <= signals):
        raise GenerationError("Analysis lacks sufficient AI model evidence (a model artifact plus a second signal) for an independent GitHub model.")
    if a.trust_remote_code and not settings.allow_remote_code:
        raise GenerationError("Analysis enables trust_remote_code, which is not allowed unless explicitly enabled in settings.")
    try:
        validate_repo_id(a.source.repo_id)
    except SecurityError as exc:
        raise GenerationError(str(exc))


def build_native_scaffold(a: Analysis) -> str:
    """The single-module source of the scaffold for an eligible independent GitHub model (same section structure as every generated app,
    so split_app_code / join_package_code / the notebook builder treat it like any other)."""
    header, setup, ui = build_native_parts(a)
    return (header.rstrip("\n") + "\n\n\n" + _SETUP_MARK + "\n" + setup.strip("\n") + "\n\n\n"
            + _UI_MARK + "\n" + ui.strip("\n") + "\n" + _LAUNCH)


def finalize_native_scaffold(a: Analysis, code: str, settings: Optional[Settings] = None) -> str:
    """The checks every generated app goes through, for the independent-GitHub scaffold: static validation of the single module and of the
    exact loader.py / app.py pair, secret scan, and requirements derived from the imports the scaffold really uses (never from the
    repository's own, unreviewed requirements). Nothing is executed. Raises GenerationError."""
    try:
        validate_app_code(code, settings)
        assert_no_secrets(code, settings)
    except (ValidationError, SecurityError) as exc:
        raise GenerationError(f"The independent GitHub scaffold failed validation: {exc}")
    if NATIVE_MARK not in code:
        raise GenerationError("The code is not an independent GitHub scaffold.")
    if "get_model" not in {n.name for n in ast.parse(code).body if isinstance(n, ast.FunctionDef)}:
        raise GenerationError("The scaffold must define a module-level get_model() loader function.")
    try:
        loader_py, app_py = split_app_code(code)
        validate_app_code(combine_package_source(app_py, loader_py), settings)
    except ValidationError as exc:
        raise GenerationError(f"The loader.py / app.py pair failed validation: {exc}")
    a.dependencies, a.dependency_evidence = [], {}  # the repository's own requirements stay in repo_requirements and are never installed
    a.dependencies, a.dependency_evidence = _with_import_requirements(a, code)
    return code


def finalize_native_generated_code(a: Analysis, code: str, settings: Optional[Settings] = None) -> str:
    """Static acceptance for native code after the adapter already proved real inference.

    Runtime validation belongs to the approved adapter, never to arbitrary generated code;
    this verifies that generated integration cannot replace it with a scaffold or unsafe loader.
    """
    from .native_readiness import require_code_generation_prerequisites
    native = a.native or {}
    require_code_generation_prerequisites(native.get("generation_evidence") or {})
    required = ("get_model", "predict", "ARTIFACT_FILE", "ARTIFACT_SHA256", "ARTIFACT_AUTHORIZED", "APPROVED_ADAPTER")
    if any(item not in code for item in required):
        raise GenerationError("Native generated code does not bind the approved artifact/inference contract.")
    if not (a.native or {}).get("runtime_validation", {}).get("artifact_verified") and "if not ARTIFACT_AUTHORIZED" not in code:
        raise GenerationError("Native candidate code must refuse model loading until its artifact is explicitly verified.")
    forbidden = ("NotImplementedError", "torch.hub", "trust_remote_code=True", "torch.load", "pickle.load", "random.")
    if any(item in code for item in forbidden):
        raise GenerationError("Native generated code contains an unsafe or placeholder inference construct.")
    try:
        validate_app_code(code, settings)
        assert_no_secrets(code, settings)
        loader_py, app_py = split_app_code(code)
        validate_app_code(combine_package_source(app_py, loader_py), settings)
    except (ValidationError, SecurityError) as exc:
        raise GenerationError(f"Native generated code failed validation: {exc}")
    a.dependencies, a.dependency_evidence = _with_import_requirements(a, code)
    return code


def check_analysis_integrity(a: Analysis, settings: Optional[Settings] = None) -> None:
    """Refuse an analysis that is internally inconsistent (stale or tampered), whatever its ``status`` claims.

    Defence in depth: the generator never trusts the Analysis object just because it says 'supported'.
    """
    settings = settings or Settings()
    if a.reasons:
        raise GenerationError("Analysis is marked generatable but still carries refusal reasons: " + "; ".join(a.reasons[:3]))
    if a.generation_blocked_reasons:
        raise GenerationError("App generation is blocked by safety eligibility checks: "
                              + "; ".join(a.generation_blocked_reasons[:3]))
    if a.origin == "github-native":
        _check_native_integrity(a, settings)
        return
    if not a.capabilities and a.task not in TASK_IO:  # legacy task-only Analysis: the reference table still gates it
        raise GenerationError("Only supported Hugging Face tasks can be generated.")
    if a.capabilities and not interface_capabilities(a):
        raise GenerationError("No capability is supported by firm evidence (all are uncertain), so no interface is generated.")
    if a.capabilities and a.capabilities[0].basis == "task" and a.task != a.capabilities[0].name:
        raise GenerationError("Analysis task does not match its primary capability.")
    if a.task in TASK_IO:
        exp_in, exp_out = _expected_io(a)
        got_in = [(i.get("name"), i.get("component")) for i in a.inputs]
        got_out = [(o.get("name"), o.get("component")) for o in a.outputs]
        if got_in != exp_in or got_out != exp_out:
            raise GenerationError(f"Analysis inputs/outputs do not match the task '{a.task}'.")
    if a.trust_remote_code and not settings.allow_remote_code:
        raise GenerationError("Analysis enables trust_remote_code, which is not allowed unless explicitly enabled in settings.")
    if not a.use_safetensors and not settings.allow_pickle_weights:
        raise GenerationError("Analysis allows pickle weights, which is not allowed unless explicitly enabled in settings.")
    ms = a.model_source
    if a.source.kind == "github":
        if ms is None or ms.kind != "huggingface":
            raise GenerationError("A GitHub analysis needs an identified linked Hugging Face model (its own code is never run).")
        pid = ms.repo_id
        role = ((a.ui_hints.get("hf_link_roles") or {}).get(pid) or {}).get("role")
        if a.primary_model != pid or pid not in a.linked_hf_models or role != "primary":
            raise GenerationError("The model to load is not the Hugging Face model identified as this repository's own.")
        if ms.canonical_url != f"https://huggingface.co/{pid}":
            raise GenerationError("The linked model reference is inconsistent.")
        if not a.revision:
            raise GenerationError("The linked Hugging Face model has no pinned commit revision.")
    elif ms is not None:
        raise GenerationError("A Hugging Face analysis must not carry a separate model source.")


