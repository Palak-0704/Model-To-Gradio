_SKELETON_PLACEHOLDERS = {"<section 1 code>", "<section 2 code>"}


def _block_locations(text: str, parts: Optional[List[str]], key: str) -> List[str]:
    """Where each `m2g:<key>` block starts, for an error message: the text part (when the reply came in several), the line within it and
    the first code line. A body that is still the format skeleton's placeholder is named as such. Diagnostic only: nothing is removed."""
    starts, pos = [], 0
    parts = parts if isinstance(parts, list) else None
    for i, part in enumerate(parts or []):  # offsets of each part inside the joined text (OpenCodeResult.text joins with one newline)
        starts.append((pos, i))
        pos += len(part) + 1
    out: List[str] = []
    for m in _SECTION_RE.finditer(text or ""):
        if m.group(1) != key:
            continue
        part_index, part_start = 0, 0
        for start, i in starts:
            if start <= m.start():
                part_index, part_start = i, start
        where = (f"text part {part_index + 1} of {len(parts)}, " if parts and len(parts) > 1 else "") \
            + f"line {(text or '').count(chr(10), part_start, m.start()) + 1}"
        body = m.group(2).strip()
        first = redact_secrets(body.splitlines()[0][:60]) if body else "(empty)"
        note = " - the unfilled format skeleton copied from the request" if body in _SKELETON_PLACEHOLDERS else ""
        out.append(f"{where}: {first!r} ({len(body.splitlines())} line(s)){note}")
    return out


def extract_sections(text: str, parts: Optional[List[str]] = None) -> Tuple[str, str]:
    """(setup, ui) from the reply. Exactly one block of each kind is required; anything else is an error, not a guess. Duplicates are
    never merged, dropped or picked between. ``parts`` (OpenCodeResult.text_parts) only lets the error say which text part and line each
    block came from."""
    found: Dict[str, List[str]] = {}
    for m in _SECTION_RE.finditer(text or ""):
        found.setdefault(m.group(1), []).append(m.group(2))
    for key in ("setup", "ui"):
        count = len(found.get(key, []))
        if count != 1:
            preview = redact_secrets(" ".join((text or "").split())[:200]) or "(empty reply)"
            where = _block_locations(text, parts, key)
            detail = (f" Blocks found: {'; '.join(where)}. A repeated block is never merged or discarded: the model must write each "
                      "labelled block exactly once.") if where else ""
            raise GenerationError(f"OpenCode's reply must contain exactly one `m2g:{key}` code block, found {count}. "
                                  f"The marker must be on the opening fence line ({_FENCE}python m2g:{key}), not in a comment "
                                  f"inside a plain python block.{detail} The reply started with: {preview}")
    return found["setup"][0], found["ui"][0]


def _parse_section(label: str, source: str) -> ast.AST:
    if not source.strip():
        raise GenerationError(f"OpenCode returned an empty {label} section.")
    if "@@" in source:
        raise GenerationError(f"The {label} section contains a template placeholder ('@@').")
    try:
        return ast.parse(source)
    except SyntaxError as exc:
        raise GenerationError(f"The {label} section is not valid Python: {exc.msg} (line {exc.lineno}).")


def _reject_unsafe_constructs(label: str, tree: ast.AST) -> None:
    """Keep the platform-owned constants and the launch block out of the model's reach."""
    protected = _PROTECTED_CONSTANTS | _PROTECTED_MODULES

    def bad(msg: str) -> None:
        raise GenerationError(f"The {label} section {msg}")

    for node in ast.walk(tree):
        if isinstance(node, ast.Name):
            if isinstance(node.ctx, (ast.Store, ast.Del)) and node.id in protected:
                bad(f"assigns to the platform-owned name {node.id!r}.")
            if node.id in _BANNED_SECTION_NAMES:
                bad(f"uses {node.id!r}, which is not allowed.")
        elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)) and node.name in protected:
            bad(f"defines {node.name!r}, a platform-owned name.")
        elif isinstance(node, ast.alias):
            if (node.asname or node.name.split(".")[0]) in _PROTECTED_CONSTANTS:
                bad("imports something under a platform-owned name.")
        elif isinstance(node, (ast.Global, ast.Nonlocal)) and set(node.names) & protected:
            bad("declares a platform-owned name global.")
        elif isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute) and node.func.attr == "launch":
            bad("calls launch(); the platform adds the launch block itself.")


