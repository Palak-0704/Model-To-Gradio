def _task_contract_lines(a: Analysis) -> List[str]:
    """Trusted loading/IO contracts for exactly the tasks (and library) this app must build."""
    lines: List[str] = []
    for lib_line in _LIBRARY_CONTRACTS.get(a.library, ()):
        lines.append(f"- Library contract ({a.library}): {lib_line}")
    seen = set()
    for c in interface_capabilities(a):
        if c.name in seen:
            continue
        if c.name in _NO_PIPELINE_TASKS and not _takes_text(c):
            seen.add(c.name)
            lines.append(f"- `{c.name}` takes {' / '.join(c.input_modalities)} input here: it is a task-conditioned mode of the primary model, not the "
                         "standalone text-to-text task. Use the primary's loader and input handling, select the mode the way `advisory` and "
                         "`model_evidence.generation.task_tokens` describe, and do not apply a text tokenizer / seq2seq contract to it.")
            continue
        if c.name not in _TASK_CONTRACTS:
            continue
        seen.add(c.name)
        lines.append(f"- Task contract for `{c.name}`:")
        lines += ["  " + text for text in _TASK_CONTRACTS[c.name]]
    if lines:
        lines = ["- Per-task loading and input/output contracts (platform-verified output shapes; follow them for the listed tasks):", *lines]
    return lines


