def _t(text: Any, limit: int = 160) -> str:
    """Repository-derived text made harmless for a docstring/comment/literal: no quotes, backslashes, markup, newlines or '@@'."""
    s = re.sub(r"[^\w .,:;()/+=%'\-@?!&~#]+", "", str(text).replace("\n", " "))
    return re.sub(r"@+", "@", s).replace("'", "")[:limit]


def _lit(items: Any, limit: int = 220, count: int = 12) -> str:
    """A Python list literal of sanitised strings (repr output is a valid, escaped literal)."""
    return repr([_t(i, limit) for i in list(items or [])[:count]])


def build_native_parts(a: Analysis) -> Tuple[str, str, str]:
    """(header, setup section, UI section) of the scaffold for an eligible github-native analysis."""
    n = a.native or {}
    warn: List[str] = ["WARNING: " + _t(w, 200) for w in a.warnings[:6] if w]
    weights = list(n.get("weight_files") or []) + list(n.get("release_weight_assets") or [])
    subs = {
        "@@URL_TXT@@": _t(a.source.canonical_url),
        "@@REV_TXT@@": _t(a.revision or "default branch (unpinned)"),
        "@@TASK_TXT@@": _t((a.task + " (inferred, confidence " + str(a.task_confidence) + ")") if a.task else "unknown"),
        "@@WARN_TXT@@": "\n".join(warn) or "Warnings: none",
        "@@MODEL_ID@@": repr(a.source.repo_id), "@@REVISION@@": repr(a.revision), "@@TASK@@": repr(_t(a.task) if a.task else None),
        "@@CONFIRMED@@": _lit(n.get("confirmed")), "@@INFERRED@@": _lit(n.get("inferred")), "@@UNKNOWN@@": _lit(n.get("unknown")),
        "@@WEIGHTS@@": _lit(weights, 160, 20),
    }
    header = _HEADER
    for k, v in subs.items():
        header = header.replace(k, v)
    return header, _SETUP, _UI
